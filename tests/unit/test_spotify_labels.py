def test_a_review_that_spotify_knows_is_not_sent_to_review(fresh_db, monkeypatch) -> None:
    pytest.importorskip("PySide6.QtCore")
    from core.discogs_store import Lookup
    from workers.discogs_worker import DiscogsWorker

    _playlist_row("/m/a.mp3", album="A", release_date="2020", label="Real Label")
    review = Lookup("/m/a.mp3", "review", 0.6, None, ())
    assert DiscogsWorker._settled_by_spotify("/m/a.mp3", review).status == "spotify"
    # a track Spotify does not know stays in the review
    review2 = Lookup("/m/zzz.mp3", "review", 0.6, None, ())
    assert DiscogsWorker._settled_by_spotify("/m/zzz.mp3", review2).status == "review"
    # a Discogs match is left alone
    matched = Lookup("/m/a.mp3", "matched", 0.95, {"label": "X"}, ())
    assert DiscogsWorker._settled_by_spotify("/m/a.mp3", matched).status == "matched"


# ── at most so many tracks per run, and the rest are not forgotten ───────────


def test_a_run_asks_spotify_about_only_so_many_tracks(fresh_db, monkeypatch) -> None:
    import workers.discogs_worker as dw

    monkeypatch.setattr(dw, "SPOTIFY_TRACKS_PER_RUN", 3)
    w, q = _worker(monkeypatch, returns=None)
    w._spotify_key = True
    for i in range(5):
        w._ask_spotify(f"/m/{i}.mp3", q)
    assert w._spotify_asked == 3
    assert w.spotify_left == 2
    # the two left over were not marked as tried: the next run takes them
    assert spotify_store.should_ask("/m/3.mp3")
    assert spotify_store.should_ask("/m/4.mp3")
    assert not spotify_store.should_ask("/m/0.mp3")  # asked, found nothing


def test_tracks_after_a_quota_stop_are_counted_as_left(fresh_db, monkeypatch) -> None:
    w, q = _worker(monkeypatch, returns=None)
    w._spotify_key = True
    w._spotify = None  # the quota stopped it
    w._ask_spotify("/m/a.mp3", q)
    assert w.spotify_left == 1


def test_a_track_that_needs_no_asking_does_not_count_against_the_cap(fresh_db, monkeypatch) -> None:
    w, q = _worker(monkeypatch, returns=None)
    w._spotify_key = True
    spotify_store.note_tried("/m/a.mp3", "no_match")
    w._ask_spotify("/m/a.mp3", q)
    assert w._spotify_asked == 0
    assert w.spotify_left == 0


def _discogs_answer(path: str, status: str) -> None:
    from core import discogs_store

    discogs_store.save(discogs_store.Lookup(path=path, status=status))


def test_a_run_with_spotify_takes_tracks_discogs_settled_but_spotify_owes(fresh_db) -> None:
    from core import discogs_store

    # Spelt as the database holds paths (the NML reader's normpath: backslashes on Windows).
    for p in (
        normpath("/m/none.mp3"),
        normpath("/m/review.mp3"),
        normpath("/m/matched.mp3"),
        normpath("/m/missed.mp3"),
    ):
        with db.get_conn() as c:
            c.execute(
                "INSERT INTO tracks (path, filename, artist, title, album, duration) VALUES (?, 'f', 'A', ?, '', 200)",
                (p, p),
            )
            c.commit()
    _discogs_answer(normpath("/m/none.mp3"), "none")
    _discogs_answer(normpath("/m/review.mp3"), "review")
    _discogs_answer(normpath("/m/matched.mp3"), "matched")
    _discogs_answer(normpath("/m/missed.mp3"), "none")
    spotify_store.note_tried(normpath("/m/missed.mp3"), "no_match")  # Spotify gave up on it

    assert discogs_store.spotify_owed() == {normpath("/m/none.mp3"), normpath("/m/review.mp3")}
    without = {p for p, _q in discogs_store.pending()}
    with_spotify = {p for p, _q in discogs_store.pending(spotify=True)}
    assert without == set()
    assert with_spotify == {normpath("/m/none.mp3"), normpath("/m/review.mp3")}


# ── Discogs first, Spotify after; the review gathers both ────────────────────


def _unsure(**kw):
    return TrackDetails(
        spotify_id="abc",
        artist="Some Artist",
        title="Some Title (Remix)",
        album="Some Album",
        release_date="2024-05-01",
        track_number=1,
        duration_s=301.0,
        label="Some Label",
        sure=False,
        **kw,
    )


def test_an_unsure_guess_is_kept_for_the_review_and_can_be_accepted(fresh_db) -> None:
    spotify_store.save_search("/m/a.mp3", _unsure())
    guess = spotify_store.unsure_guesses()[normpath("/m/a.mp3")]
    assert guess.label == "Some Label" and not guess.sure
    assert spotify_store.should_ask("/m/a.mp3") is False  # tried, not asked again
    assert spotify_store.accept_guess(normpath("/m/a.mp3"))
    assert normpath("/m/a.mp3") not in spotify_store.unsure_guesses()
    assert spotify_store.settles(normpath("/m/a.mp3"))


def test_a_rejected_guess_leaves_the_review_and_is_not_asked_again(fresh_db) -> None:
    spotify_store.save_search("/m/a.mp3", _unsure())
    spotify_store.reject_guess("/m/a.mp3")
    assert spotify_store.unsure_guesses() == {}
    assert not spotify_store.should_ask("/m/a.mp3")


def test_the_review_holds_doubtful_discogs_tracks_and_spotifys_unsure_guesses(fresh_db) -> None:
    from core import discogs_store

    # Spelt as the database holds paths (the NML reader's normpath: backslashes on Windows).
    for p in (normpath("/m/d.mp3"), normpath("/m/s.mp3"), normpath("/m/m.mp3")):
        with db.get_conn() as c:
            c.execute(
                "INSERT INTO tracks (path, filename, artist, title, album, duration) "
                "VALUES (?, 'f', 'A', ?, '', 200)",
                (p, p),
            )
            c.commit()
    discogs_store.save(discogs_store.Lookup(path=normpath("/m/d.mp3"), status="review"))
    discogs_store.save(discogs_store.Lookup(path=normpath("/m/m.mp3"), status="matched"))
    spotify_store.save_search(normpath("/m/s.mp3"), _unsure())
    spotify_store.save_search(normpath("/m/m.mp3"), _unsure())  # Discogs has it: not in the review
    assert discogs_store.review_paths() == {normpath("/m/d.mp3"), normpath("/m/s.mp3")}


def test_spotify_is_asked_after_discogs_and_settles_a_review(fresh_db, monkeypatch) -> None:
    from core import discogs_store

    w, q = _worker(monkeypatch, returns=None)
    w._spotify_key = True
    discogs_store.save(discogs_store.Lookup(path="/m/a.mp3", status="review"))
    asked: list[str] = []
    monkeypatch.setattr(w, "_ask_spotify", lambda path, _q: asked.append(path))
    monkeypatch.setattr(spotify_store, "settles", lambda _p: True)
    w._unsettled.append(("/m/a.mp3", q))
    w.outcome["review"] = 1
    w._spotify_phase()
    assert asked == ["/m/a.mp3"]
    assert discogs_store.get("/m/a.mp3").status == "spotify"  # settled, out of the review
    assert w.outcome["review"] == 0 and w.outcome["spotify"] == 1
