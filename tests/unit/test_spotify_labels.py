# ── the label, from a copyright line ─────────────────────────────────────────


@pytest.mark.parametrize(
    ("text", "label"),
    [
        ("℗ 2017 Ninja Tune", "Ninja Tune"),
        ("(P) 2023 Mutual Rytm", "Mutual Rytm"),
        ("2021 Isaiah. All Rights Reserved", "Isaiah"),
        ("℗ 2020 Arcade Fire Music Under Exclusive License to Sony Music Entertainment", "Arcade Fire Music"),
        ("© 2019 Soma Quality Recordings, distributed by Believe", "Soma Quality Recordings"),
        ("℗ 2022 Believe", ""),  # a distributor
        ("℗ 2022 FUGA", ""),
        ("℗ 2018 2429111 Records DK", ""),  # generated by a self-distribution service
        ("℗ 2023 AKIVV011", ""),  # a catalogue number
        ("ISH11", "ISH11"),  # a short label name is not a catalogue number
        ("UFO Inc.", "UFO Inc."),  # a name's own full stop stays
        ("Smile Sessions - all rights reserved", "Smile Sessions"),
        ("℗ Night Service, All Rights Reserved", "Night Service"),
        ("All rights reserved to Format Records", "Format Records"),
        ("©Vibrant Collective 2023", "Vibrant Collective"),
        ("Frenzy Recordings 2024. All rights of the producer reserved. Unauthorised copying prohibited.", "Frenzy Recordings"),
        ("", ""),
    ],
)  # fmt: skip
def test_clean_label(text: str, label: str) -> None:
    assert clean_label(text) == label


def test_label_of_takes_the_p_line_and_skips_a_distributor() -> None:
    lines = [
        {"type": "C", "text": "© 2020 Some Imprint"},
        {"type": "P", "text": "℗ 2020 Believe"},
    ]
    assert label_of(lines) == "Some Imprint"  # the ℗ line names a distributor: the © line is next


# ── which tracks are still asked about ───────────────────────────────────────


def _playlist_row(path: str, **fields) -> None:
    with db.get_conn() as c:
        c.execute(
            "INSERT INTO track_spotify (path, spotify_id, artist, title, album, release_date, "
            "label, synced_at, source, sure) VALUES (?,?,?,?,?,?,?,?, 'playlist', 1)",
            (
                normpath(path),
                "id1",
                "Artist",
                "Title",
                fields.get("album"),
                fields.get("release_date"),
                fields.get("label"),
                0.0,
            ),
        )
        c.commit()


def _details(sure: bool = True, label: str = "Real Label") -> TrackDetails:
    return TrackDetails(
        spotify_id="id1",
        artist="Artist",
        title="Title",
        album="The Album",
        release_date="2024-05-01",
        track_number=1,
        duration_s=300.0,
        label=label,
        sure=sure,
    )


def test_a_new_track_is_asked(fresh_db) -> None:
    assert spotify_store.should_ask("/m/new.mp3")


def test_a_playlist_track_with_no_details_is_still_asked(fresh_db) -> None:
    _playlist_row("/m/a.mp3")  # the public page gave artist and title only
    assert spotify_store.has("/m/a.mp3")
    assert spotify_store.should_ask("/m/a.mp3")


def test_a_track_with_album_date_and_label_is_not_asked(fresh_db) -> None:
    _playlist_row("/m/a.mp3", album="A", release_date="2020", label="L")
    assert not spotify_store.should_ask("/m/a.mp3")
    assert not spotify_store.should_ask("/m/a.mp3", again=True)  # complete: never asked again


def test_a_playlist_row_with_a_date_but_no_label_is_asked(fresh_db) -> None:
    _playlist_row("/m/a.mp3", album="A", release_date="2020")
    assert spotify_store.should_ask("/m/a.mp3")


def test_a_miss_is_remembered_until_asked_again(fresh_db) -> None:
    spotify_store.note_tried("/m/x.mp3", "no_match")
    assert not spotify_store.should_ask("/m/x.mp3")
    assert spotify_store.should_ask("/m/x.mp3", again=True)
    assert spotify_store.forget_tried() == 1
    assert spotify_store.should_ask("/m/x.mp3")


# ── what a search may add to a playlist track ────────────────────────────────


def test_a_sure_search_fills_only_the_empty_fields_of_a_playlist_row(fresh_db) -> None:
    _playlist_row("/m/a.mp3", album="Kept Album")
    spotify_store.save_search("/m/a.mp3", _details())
    with db.get_conn() as c:
        row = c.execute(
            "SELECT * FROM track_spotify WHERE path = ?", (normpath("/m/a.mp3"),)
        ).fetchone()
    assert row["album"] == "Kept Album"  # never overwritten
    assert row["release_date"] == "2024-05-01"
    assert row["label"] == "Real Label"
    assert row["source"] == "playlist"
    assert not spotify_store.should_ask("/m/a.mp3")


def test_an_unsure_search_leaves_a_playlist_row_alone_and_is_remembered(fresh_db) -> None:
    _playlist_row("/m/a.mp3")
    spotify_store.save_search("/m/a.mp3", _details(sure=False))
    with db.get_conn() as c:
        row = c.execute(
            "SELECT * FROM track_spotify WHERE path = ?", (normpath("/m/a.mp3"),)
        ).fetchone()
    assert row["release_date"] is None and row["label"] is None
    assert not spotify_store.should_ask("/m/a.mp3")  # tried; "Look up again" retries


def test_infos_drops_a_distributor_saved_before_the_cleaning_existed(fresh_db) -> None:
    _playlist_row("/m/a.mp3", album="A", release_date="2020", label="Believe")
    _playlist_row("/m/b.mp3", album="A", release_date="2020", label="Ninja Tune")
    got = spotify_store.infos()
    assert got[normpath("/m/a.mp3")].label == ""
    assert got[normpath("/m/b.mp3")].label == "Ninja Tune"


# ── the worker: a quota block, and remembering misses ────────────────────────


class _Limiter:
    def __init__(self) -> None:
        self.paused: list[float] = []

    def acquire(self, _stop) -> bool:
        return True

    def pause(self, seconds: float) -> None:
        self.paused.append(seconds)


def _worker(monkeypatch, raises=None, returns=None):
    pytest.importorskip("PySide6.QtCore")
    import core.spotify_api as api
    from core.discogs_match import Query
    from workers.discogs_worker import DiscogsWorker

    def lookup(*_a, **_k):
        if raises is not None:
            raise raises
        return returns

    monkeypatch.setattr(api, "lookup_track", lookup)
    w = DiscogsWorker([])
    w._spotify = _Limiter()
    return w, Query("Artist", "Title", "", 300.0)


def test_a_day_long_retry_after_stops_asking_spotify(fresh_db, monkeypatch) -> None:
    from core.spotify import SpotifyHTTPError

    w, q = _worker(monkeypatch, raises=SpotifyHTTPError(429, "Spotify said 429", 85560.0))
    w._ask_spotify("/m/a.mp3", q)
    assert w._spotify is None
    assert spotify_store.should_ask("/m/a.mp3")  # an error is not a miss


def test_a_short_retry_after_pauses_and_goes_on(fresh_db, monkeypatch) -> None:
    from core.spotify import SpotifyHTTPError

    w, q = _worker(monkeypatch, raises=SpotifyHTTPError(429, "Spotify said 429", 12.0))
    limiter = w._spotify
    w._ask_spotify("/m/a.mp3", q)
    assert w._spotify is limiter
    assert limiter.paused == [12.0]


def test_a_track_spotify_cannot_find_is_not_searched_again(fresh_db, monkeypatch) -> None:
    w, q = _worker(monkeypatch, returns=None)
    w._ask_spotify("/m/a.mp3", q)
    assert not spotify_store.should_ask("/m/a.mp3")


